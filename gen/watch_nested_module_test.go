// writeNestedReplaceFixture builds the in-tree replace-target layout this file
// exercises:
//
//	root/go.mod          module example.com/m, replace example.com/extra => ./extra
//	root/extra/go.mod    module example.com/extra   (a NESTED module)
//	root/extra/extra.go  authored Go the main module consumes through the replace
//	root/extra/widget.gsx a .gsx package owned by the NESTED module
//	root/views/page.gsx  main-module page rendering extra.Label()
//
// Both modules replace the gsx runtime to this checkout so generated output
// compiles against the same runtime the corpus uses.
func writeNestedReplaceFixture(t *testing.T, root string) {
	t.Helper()
	gsxDir := gsxModuleDir(t)
	writeFileT(t, filepath.Join(root, "go.mod"),
		"module example.com/m\n\ngo 1.26.1\n\nrequire (\n\tgithub.com/gsxhq/gsx v0.0.0\n\texample.com/extra v0.0.0\n)\n\nreplace github.com/gsxhq/gsx => "+gsxDir+"\n\nreplace example.com/extra => ./extra\n")
	writeFileT(t, filepath.Join(root, "extra", "go.mod"),
		"module example.com/extra\n\ngo 1.26.1\n\nrequire github.com/gsxhq/gsx v0.0.0\n\nreplace github.com/gsxhq/gsx => "+gsxDir+"\n")
	writeFileT(t, filepath.Join(root, "extra", "extra.go"),
		"package extra\n\nfunc Label() string { return \"hi\" }\n")
	writeFileT(t, filepath.Join(root, "extra", "widget.gsx"),
		"package extra\n\ncomponent Widget() {\n\t<b>one</b>\n}\n")
	writeFileT(t, filepath.Join(root, "views", "page.gsx"),
		"package views\n\nimport \"example.com/extra\"\n\ncomponent Page() {\n\t<p>{extra.Label()}</p>\n}\n")
}

// TestWatchSession_NestedReplaceTargetGoEdit pins the routing for an authored
// .go edit inside a NESTED module that the watched main module consumes
// through a go.mod `replace … => ./extra`.
//
// The in-place goDirty path refreshes exactly one Module — the one rooted at
// the file's NEAREST go.mod, i.e. the nested module. The main module's own
// source manifest structurally cannot observe that file (sourceview stops at
// every nested go.mod, and RefreshDiskSourcesAndInvalidate rejects a dir the
// root does not own), so every later regeneration in the main module kept
// generating against the pre-edit types: silently wrong output rather than a
// build error (a string→int Label() kept emitting `Text(string(...))`, which
// still compiles and renders "*").
//
// The cycle must therefore escalate to depDirty/reopen, which is what the
// pre-goDirty classification did for every .go edit. The control half of the
// test pins the escalation's scope: a .gsx edit in that SAME nested-module dir
// must still stay warm and closure-scoped.
func TestWatchSession_NestedReplaceTargetGoEdit(t *testing.T) {
	if testing.Short() {
		t.Skip("real module analysis")
	}
	t.Parallel()
	root := t.TempDir()
	writeNestedReplaceFixture(t, root)

	extraDir := filepath.Join(root, "extra")
	viewsDir := filepath.Join(root, "views")

	sess, startup, err := startWatchSessionForTest(watchConfig{paths: []string{root}})
	if err != nil {
		t.Fatalf("startWatchSessionForTest: %v", err)
	}
	for _, r := range startup {
		if !r.OK {
			t.Fatalf("startup regen not OK: dir=%s err=%v diags=%v", r.Dir, r.Err, r.Diags)
		}
	}
	pagePath := filepath.Join(viewsDir, "page.x.go")
	before, err := os.ReadFile(pagePath)
	if err != nil {
		t.Fatalf("reading page.x.go after startup: %v", err)
	}

	// Route events exactly as the live loop does: the tracker owns
	// classification, so the escalation decision under test is the production
	// one, not a hand-set dirty flag.
	sources, err := newSourceTracker(sess.watchRoots, sess.requestedRoots, sess)
	if err != nil {
		t.Fatalf("newSourceTracker: %v", err)
	}
	dirty := newWatchDirtySet()

	// Phase 1: signature change in the replace target. string -> int keeps
	// {extra.Label()} compiling, so a stale world produces wrong OUTPUT rather
	// than a diagnostic — the assertion below is on generated bytes.
	writeFileT(t, filepath.Join(extraDir, "extra.go"),
		"package extra\n\nfunc Label() int { return 42 }\n")
	if !queueWatchSource(filepath.Join(extraDir, "extra.go"), sources, dirty) {
		t.Fatal("edited extra.go did not queue as a watchable source event")
	}
	if !dirty.depDirty {
		t.Fatal("a .go edit in a nested replace-target module must escalate to depDirty: the main module's manifest cannot observe it, so the in-place goDirty refresh leaves every dependent generating against stale types")
	}

	if _, _, err := dirty.regenerate(sess.regenPending); err != nil {
		t.Fatalf("regenerate after nested replace-target go edit: %v", err)
	}
	after, err := os.ReadFile(pagePath)
	if err != nil {
		t.Fatalf("reading page.x.go after the nested go edit: %v", err)
	}
	if string(before) == string(after) {
		t.Fatal("page.x.go is byte-identical after extra.Label() changed string -> int: the main module regenerated against a stale world")
	}
	if !strings.Contains(string(after), "IntInto") {
		t.Fatalf("expected an int-typed writer call after the signature change, got:\n%s", after)
	}

	// Phase 2 (control): a .gsx edit in the SAME nested-module dir must NOT
	// escalate. Nested modules legitimately own .gsx packages, and their own
	// warm Module regenerates them correctly; escalating every such edit to a
	// full session reopen would be a plain perf regression.
	widgetPath := filepath.Join(extraDir, "widget.gsx")
	widgetOut := filepath.Join(extraDir, "widget.x.go")
	writeFileT(t, widgetPath, "package extra\n\ncomponent Widget() {\n\t<b>two</b>\n}\n")
	if !queueWatchSource(widgetPath, sources, dirty) {
		t.Fatal("edited widget.gsx did not queue as a watchable source event")
	}
	if dirty.depDirty || dirty.goDirty {
		t.Fatalf("a .gsx edit in a nested module must stay warm: depDirty=%v goDirty=%v", dirty.depDirty, dirty.goDirty)
	}
	results, _, err := dirty.regenerate(sess.regenPending)
	if err != nil {
		t.Fatalf("regenerate after nested-module gsx edit: %v", err)
	}
	for _, r := range results {
		if r.Dir == viewsDir {
			t.Fatalf("nested-module .gsx edit regenerated the unrelated main-module dir %s — the cycle reopened instead of staying closure-scoped", viewsDir)
		}
	}
	widget, err := os.ReadFile(widgetOut)
	if err != nil {
		t.Fatalf("reading widget.x.go after the nested gsx edit: %v", err)
	}
	if !strings.Contains(string(widget), "two</b>") {
		t.Fatalf("widget.x.go was not regenerated warm from the nested module:\n%s", widget)
	}
}

// TestWatchSession_VendoredGoEditDoesNotWedgeTheCycle pins the second
// ownership boundary. A vendored .go file is attributed by moduleRoot to the
// enclosing module — vendoring writes no go.mod — but that module cannot
// refresh it: sourceview's ownership oracle rejects any path with a vendor
// segment, exactly as it rejects a nested module. Routed as an ordinary
// in-place go edit, regenPending's refresh returned that rejection as a cycle
// error, which RETAINS the dirty transaction: every later fire replayed the
// same pending dir and failed again, wedging the session until restart. One
// `go mod vendor` is enough to trigger it.
//
// A vendored write IS dependency-surface movement, so escalating it to the
// reopen is both safe and what the pre-goDirty classification did. Discovery
// skips vendor (gen/gen.go skipDirs), so the reopen itself never touches it.
//
// The fixture nests vendor/ under a subdirectory — see
// TestLSPRefreshDiskSkipsUnrefreshableGoPaths for why a root vendor/ cannot be
// built here; the oracle keys on the path segment either way.
func TestWatchSession_VendoredGoEditDoesNotWedgeTheCycle(t *testing.T) {
	if testing.Short() {
		t.Skip("real module analysis")
	}
	t.Parallel()
	root := t.TempDir()
	writeMod(t, root)
	writeFileT(t, filepath.Join(root, "views", "page.gsx"),
		"package views\n\ncomponent Page() {\n\t<p>one</p>\n}\n")
	vendorGo := filepath.Join(root, "lib", "vendor", "example.com", "third", "party.go")
	writeFileT(t, vendorGo, "package party\n\nfunc Value() string { return \"v1\" }\n")

	sess, startup, err := startWatchSessionForTest(watchConfig{paths: []string{root}})
	if err != nil {
		t.Fatalf("startWatchSessionForTest: %v", err)
	}
	for _, r := range startup {
		if !r.OK {
			t.Fatalf("startup regen not OK: dir=%s err=%v diags=%v", r.Dir, r.Err, r.Diags)
		}
	}

	sources, err := newSourceTracker(sess.watchRoots, sess.requestedRoots, sess)
	if err != nil {
		t.Fatalf("newSourceTracker: %v", err)
	}
	dirty := newWatchDirtySet()
	writeFileT(t, vendorGo, "package party\n\nfunc Value() int { return 2 }\n")
	if !queueWatchSource(vendorGo, sources, dirty) {
		t.Fatal("edited vendored .go did not queue as a watchable source event")
	}
	if !dirty.depDirty {
		t.Fatal("a vendored .go edit must escalate to depDirty: the enclosing module cannot refresh a vendor dir, so the in-place path can only fail the cycle")
	}

	if _, _, err := dirty.regenerate(sess.regenPending); err != nil {
		t.Fatalf("regenerate after a vendored .go edit: %v", err)
	}
	if len(dirty.dirs) != 0 || len(dirty.goDirs) != 0 || dirty.depDirty || dirty.goDirty {
		t.Fatalf("the cycle did not commit: dirs=%v goDirs=%v depDirty=%v goDirty=%v — a retained transaction replays and fails forever", dirty.dirs, dirty.goDirs, dirty.depDirty, dirty.goDirty)
	}
}

// TestGoEditNeedsReopen pins the escalation predicate itself, without paying
// for a warm Module: only a dir whose owning module is NOT the session module
// that CONTAINS it escalates. Sibling module roots are independent — an edit
// in module B's dir is served correctly by B's own Module — and the
// single-module session (the overwhelmingly common case) exits right after
// the ownership probe, before the containment loop.
func TestGoEditNeedsReopen(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeFileT(t, filepath.Join(root, "go.mod"), "module example.com/m\n\ngo 1.26.1\n")
	nested := filepath.Join(root, "extra")
	writeFileT(t, filepath.Join(nested, "go.mod"), "module example.com/extra\n\ngo 1.26.1\n")
	sibling := filepath.Join(t.TempDir(), "beta")
	writeFileT(t, filepath.Join(sibling, "go.mod"), "module example.com/beta\n\ngo 1.26.1\n")

	unowned := t.TempDir() // no go.mod anywhere above it

	cases := []struct {
		name  string
		roots []string
		dir   string
		want  bool
	}{
		{"single module session never escalates", []string{root}, filepath.Join(root, "dep"), false},
		{"main-module dir of a nested layout stays warm", []string{root, nested}, filepath.Join(root, "dep"), false},
		{"nested replace-target dir escalates", []string{root, nested}, nested, true},
		{"dir below a nested module escalates", []string{root, nested}, filepath.Join(nested, "sub"), true},
		{"sibling module dir stays warm", []string{root, sibling}, filepath.Join(sibling, "dep"), false},
		// The ownership oracle's second boundary: no session module can
		// refresh a vendor dir, so the in-place path has nothing to route to.
		{"vendored dir escalates in a single-module session", []string{root}, filepath.Join(root, "vendor", "x", "y"), true},
		{"vendored dir nested under a package escalates", []string{root}, filepath.Join(root, "lib", "vendor", "x"), true},
		{"dir with no module above it escalates", []string{root}, unowned, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			s := &watchSession{roots: c.roots}
			if got := s.goEditNeedsReopen(c.dir); got != c.want {
				t.Fatalf("goEditNeedsReopen(%q) with roots %v = %v, want %v", c.dir, c.roots, got, c.want)
			}
		})
	}
	var nilSession *watchSession
	if nilSession.goEditNeedsReopen(root) {
		t.Fatal("a nil session must never escalate")
	}
}
